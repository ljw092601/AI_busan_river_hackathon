/** SPOT_IDS에 있는데 `spots` 배열에 빠진 스팟이 있으면 여기서 컴파일 에러가 납니다. */
export type NoMissingSpotEntry = AssertNever<Exclude<SpotId, (typeof spots)[number]['id']>>;

